/* Boot — registers the chapters that exist on the page, then wires the rail, HUD, readout, decode
   wipe for long jumps, the capsule that carries the next chapter's name into its kicker, grain
   and the motion switch. CHAPTERS is generated by build.mjs from the <!--ch-x--> sections of
   page.html (ch-foo-bar → global ChFooBar); missing modules are skipped, so --only pages work. */

const CHAPTERS = [
/*__CHAPTERS__*/
].filter(([id, mod]) => mod && document.getElementById(id));

for (const [, mod] of CHAPTERS) mod.build?.();

/** One rail entry per label in data-chapter ("00|NAME|desc@0;01|NAME|desc@0.55"). */
const marks = [];
for (const [id, mod] of CHAPTERS) {
  const s = Engine.add({
    id,
    update: (p, scene) => mod.update?.(p, scene),
    resize: (scene) => mod.resize?.(scene),
    show: (scene) => mod.show?.(scene),
    hide: (scene) => mod.hide?.(scene),
  });
  for (const part of s.el.dataset.chapter.split(";")) {
    const [head, at] = part.split("@");
    const [num, name, desc] = head.split("|");
    marks.push({ id, num, name, desc, at: Number(at || 0), s });
  }
}
const sceneOf = (id) => Engine.scenes.find((x) => x.id === id);
const total = $("#hudTotal");
if (total && marks.length) total.textContent = marks[marks.length - 1].num;

/* ── decode wipe for long jumps ── */
const wipe = $("#wipe");
const wipeCv = $("#wipeCanvas");
const wipeText = $("#wipeText");
let wiping = false;
function paintWipe() {
  const w = innerWidth;
  const h = innerHeight;
  const d = Math.min(1.5, devicePixelRatio || 1);
  wipeCv.width = Math.round(w * d);
  wipeCv.height = Math.round(h * d);
  const c = wipeCv.getContext("2d");
  c.setTransform(d, 0, 0, d, 0, 0);
  c.fillStyle = "#050504";
  c.fillRect(0, 0, w, h);
  c.font = "500 13px JetBrains Mono, monospace";
  const R = rng(11);
  for (let y = 22; y < h; y += 22)
    for (let x = 12; x < w; x += 30) {
      const v = (R() * 256) | 0;
      c.fillStyle = R() < 0.035 ? "rgba(255,90,42,.8)" : "rgba(239,234,220,.26)";
      c.fillText(v.toString(16).padStart(2, "0"), x, y);
    }
}
const animateMs = (ms, fn) =>
  new Promise((res) => {
    const t0 = performance.now();
    const step = (now) => {
      const k = clamp((now - t0) / ms);
      fn(E.lock(k));
      k < 1 ? requestAnimationFrame(step) : res();
    };
    requestAnimationFrame(step);
  });
async function jump(id, at = 0) {
  const s = sceneOf(id);
  if (!s) return;
  const top = s.top + Math.max(0, s.h - Engine.vh) * at;
  if (Engine.reduce || Math.abs(top - scrollY) < Engine.vh * 1.5 || wiping) {
    scrollTo({ top, behavior: Engine.reduce ? "auto" : "smooth" });
    return;
  }
  wiping = true;
  paintWipe();
  wipe.classList.add("is-on");
  const mark = marks.find((m) => m.id === id);
  wipeText.textContent = `JUMP · ${mark ? `${mark.num} ${mark.desc}` : id}`;
  await animateMs(360, (k) => {
    wipe.style.setProperty("--a", "0%");
    wipe.style.setProperty("--b", `${(1 - k) * 100}%`);
    wipe.style.setProperty("--y", `${k * 100}%`);
  });
  scrollTo({ top, behavior: "instant" });
  await new Promise((r) => setTimeout(r, 110));
  await animateMs(440, (k) => {
    wipe.style.setProperty("--a", `${k * 100}%`);
    wipe.style.setProperty("--b", "0%");
    wipe.style.setProperty("--y", `${k * 100}%`);
  });
  wipe.classList.remove("is-on");
  wiping = false;
}
window.jumpTo = jump;

const rail = $("#rail");
rail.innerHTML = marks
  .map((m, i) => `<li><a href="#${m.id}" data-i="${i}"><span>${m.num} ${m.desc}</span><i></i></a></li>`)
  .join("");
rail.addEventListener("click", (event) => {
  const a = event.target.closest("a");
  if (!a) return;
  event.preventDefault();
  const m = marks[Number(a.dataset.i)];
  jump(m.id, m.at);
});
document.addEventListener("click", (event) => {
  const a = event.target.closest("[data-jump]");
  if (!a) return;
  event.preventDefault();
  jump(a.dataset.jump, Number(a.dataset.at || 0));
});
const railLinks = $$("a", rail);

/* ── grain ── */
(() => {
  const c = document.createElement("canvas");
  c.width = c.height = 180;
  const g = c.getContext("2d");
  const img = g.createImageData(180, 180);
  for (let i = 0; i < img.data.length; i += 4) {
    const v = (Math.random() * 255) | 0;
    img.data[i] = img.data[i + 1] = img.data[i + 2] = v;
    img.data[i + 3] = 255;
  }
  g.putImageData(img, 0, 0);
  $("#grain").style.backgroundImage = `url(${c.toDataURL()})`;
})();
const grain = $("#grain");
let grainT = 0;

/* ── capsule: the next chapter's name flies from the previous stage into its kicker ── */
const carrier = $("#carrier");
const carrierText = $("#carrierText");

const hudNum = $("#hudNum");
const hudName = $("#hudName");
const roLeft = $("#roLeft");
const roRight = $("#roRight");
let cur = -1;
Engine.on((E2) => {
  const mid = E2.y + E2.vh * 0.5;
  let ci = 0;
  marks.forEach((m, i) => {
    if (mid >= m.s.top + Math.max(0, m.s.h - E2.vh) * m.at) ci = i;
  });
  if (ci !== cur && marks[ci]) {
    cur = ci;
    hudNum.textContent = marks[ci].num;
    hudName.textContent = marks[ci].name;
    railLinks.forEach((a, i) => (i === ci ? a.setAttribute("aria-current", "step") : a.removeAttribute("aria-current")));
  }
  const m = marks[ci];
  if (m) {
    const org = m.s.el.dataset.org;
    const period = m.s.el.dataset.period;
    setText(roLeft, [org, period].filter(Boolean).join(" · ") || document.title.split(" — ")[0]);
    setText(roRight, `P ${m.s.p.toFixed(3)} · ${m.num} ${m.desc}`);
  }

  // Capsule between two product chapters (desktop, motion on).
  let shown = false;
  if (!E2.reduce && !E2.mobile) {
    for (let i = 1; i < CHAPTERS.length; i++) {
      const s = sceneOf(CHAPTERS[i][0]);
      if (!s || s.enter <= 0.04 || s.enter >= 0.98 || !s.el.dataset.org) continue;
      const kicker = $(".ch-copy .kicker", s.el);
      const prev = sceneOf(CHAPTERS[i - 1][0])?.el || document.body;
      const from = $("[data-capsule-from]", prev) || $(".ch-product", prev);
      if (!kicker || !from) continue;
      const A = from.getBoundingClientRect();
      const B = kicker.getBoundingClientRect();
      if (!A.width || !B.width) continue;
      const e = E.travel(clamp((s.enter - 0.06) / 0.88));
      const ax = A.left + A.width / 2;
      const ay = A.top + A.height / 2;
      const bx = B.left + 90;
      const by = B.top + B.height / 2;
      const arc = Math.sin(e * Math.PI) * 140;
      setText(carrierText, `${s.el.dataset.org} · ${s.el.dataset.chapter.split("|")[2].split("@")[0]}`);
      carrier.style.transform = `translate3d(${lerp(ax, bx, e).toFixed(1)}px,${(lerp(ay, by, e) - arc).toFixed(1)}px,0) translate(-50%,-50%) scale(${(1 + Math.sin(e * Math.PI) * 0.12).toFixed(3)})`;
      carrier.style.opacity = String(Math.min(1, (s.enter - 0.04) * 10, (0.98 - s.enter) * 10));
      shown = true;
      break;
    }
  }
  if (!shown) carrier.style.opacity = "0";

  if (!E2.reduce && E2.t - grainT > 0.09) {
    grainT = E2.t;
    grain.style.backgroundPosition = `${(Math.random() * 180) | 0}px ${(Math.random() * 180) | 0}px`;
  }
});

Engine.start();
